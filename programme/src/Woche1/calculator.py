number1 = input('Bitte die erste Zahl eingeben: ')
number2 = input('Bitte die zweite Zahl eingeben: ')
number1 = float(number1)
number2 = float(number2)

result_sum = number1 + number2
print('Die Summe der Zahlen ' + str(number1) + ' und ' + str(number2) + ' ist ' + str(result_sum))

result_diff = number1 - number2
print(f'Die Differenz der Zahlen {number1} und {number2} ist {result_diff}')

result_times = number1 * number2
print(f'Das Produkt der Zahlen {number1} und {number2} ist {result_times}')

print(f'Der Quotient der Zahlen {number1} und {number2} ist {number1 / number2}') # Jawohl, in den geschweiften Klammern kann man Aktionen ausführen



